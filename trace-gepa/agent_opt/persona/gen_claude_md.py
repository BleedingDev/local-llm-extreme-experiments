"""Generate a data-grounded CLAUDE.md from the persona profile.

Usage:
    .venv-gepa/bin/python -m agent_opt.persona.gen_claude_md \\
        --profile trace-gepa/agent_opt/persona/profile.json \\
        --output  trace-gepa/artifacts/CLAUDE.generated.md
"""
from __future__ import annotations

import argparse
import datetime
import json
import pathlib
import re


def _read_json(path: pathlib.Path) -> dict:
    return json.loads(path.read_text())


def _split_preserve_handedits(existing: str) -> str:
    marker = "<!-- AUTO-EDITS-BELOW:"
    idx = existing.find(marker)
    if idx == -1:
        return ""
    nl = existing.find("\n", idx)
    return existing[nl + 1 :] if nl != -1 else ""


def render(profile: dict) -> str:
    top_tools = (profile.get("tool_histogram_top10") or [])[:5]
    top_bash = (profile.get("bash_verb_top20") or [])[:8]
    top_paths = (profile.get("path_histogram") or [])[:3]
    top_repo = (profile.get("repo_top5") or [])[:3]
    recovery = (profile.get("recovery_top5") or [])[:5]
    cz = ((profile.get("language_signals") or {}).get("czech_token_counts") or [])[:6]
    summary = profile.get("summary") or {}
    sessions = summary.get("sessions", "?")
    records = summary.get("records", "?")
    now = datetime.datetime.now().isoformat(timespec="seconds")

    out = []
    out.append(
        "<!-- AUTO-GENERATED by trace-gepa/agent_opt/persona/gen_claude_md.py -->"
    )
    out.append(
        f"<!-- Source: agent_opt/persona/profile.json ({sessions} sessions / {records} records) -->"
    )
    out.append(f"<!-- Generated: {now} -->")
    out.append(
        "<!-- Hand-edits below the AUTO-EDITS-BELOW marker are preserved across regenerations. -->"
    )
    out.append("")
    out.append("# Personalised CLAUDE.md (data-grounded)")
    out.append("")
    out.append(
        "This file is generated from the user's actual trace history. Numbers in brackets are observed event counts."
    )
    out.append("")
    out.append("## Tool reaches")
    out.append("")
    out.append("The user reaches for these tools first (top by usage):")
    for name, count in top_tools:
        out.append(f"- `{name}` ({count})")
    out.append("")
    out.append("## Bash command preferences")
    out.append("")
    for verb, count in top_bash:
        out.append(f"- `{verb}` ({count})")
    out.append("")
    out.append(
        "**Package manager**: pnpm (not bun — bun is absent from the top-20)."
    )
    out.append("**Search tool**: grep (2173) over rg (108) by ~20:1.")
    out.append("")
    out.append("## Workspace")
    out.append("")
    for path, count in top_paths:
        out.append(f"- `{path}` ({count})")
    out.append("")
    out.append("Primary repos:")
    for repo, count in top_repo:
        out.append(f"- `{repo}` ({count})")
    out.append("")
    out.append("## Recovery reflexes")
    out.append("")
    out.append("Top observed transformations when an action fails:")
    for r in recovery:
        failed = r.get("failed") or "?"
        rec = r.get("recovered") or "?"
        cnt = r.get("count") or "?"
        out.append(f"- `{failed}` → `{rec}` ({cnt}×)")
    out.append("")
    out.append("## Authoritative override signals (Czech)")
    out.append("")
    out.append(
        "When the user starts a message with any of these tokens, treat it as authoritative correction:"
    )
    for tok, count in cz:
        out.append(f"- `{tok}` ({count})")
    out.append("")
    out.append("## Antipatterns to avoid")
    out.append("")
    out.append("Based on observed `failure_category` distribution in the dataset:")
    out.append(
        "- `bash_exit_nonzero`: don't retry the identical failing command — diagnose first"
    )
    out.append(
        "- `cmd_not_found_127`: verify binaries are on PATH before invoking"
    )
    out.append(
        "- `hallucinated_path`: prefer Glob/Grep to verify a path exists before Read"
    )
    out.append(
        "- `hallucinated_skill`: only invoke skills listed in the active skill_listing"
    )
    out.append(
        "- `cancelled_parallel_batch`: don't fan out heavy I/O in parallel tool calls"
    )
    out.append("")
    out.append(
        "<!-- AUTO-EDITS-BELOW: hand-written content goes below this marker and is preserved on regeneration -->"
    )
    return "\n".join(out) + "\n"


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument(
        "--profile",
        default="trace-gepa/agent_opt/persona/profile.json",
        type=pathlib.Path,
    )
    p.add_argument(
        "--output",
        default="trace-gepa/artifacts/CLAUDE.generated.md",
        type=pathlib.Path,
    )
    args = p.parse_args()

    profile = _read_json(args.profile)
    rendered = render(profile)

    if args.output.exists():
        existing = args.output.read_text()
        preserved = _split_preserve_handedits(existing)
        if preserved.strip():
            rendered = rendered + preserved

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered)
    print(f"wrote {args.output} ({len(rendered)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
