import { parseJsonObject, type LlmRouter } from "./llm";
import { PrdArtifactSchema, PrdSectionKeySchema, type InterviewTurn, type PrdArtifact } from "./types";

const SECTION_TITLES: Record<PrdArtifact["sections"][number]["key"], string> = {
  table_of_contents: "Table of Contents",
  users_and_jobs: "Users and Jobs",
  problem_statement: "Problem Statement",
  product_scope: "Product Scope",
  user_workflows: "User Workflows",
  functional_requirements: "Functional Requirements",
  integrations_and_constraints: "Integrations and Constraints",
  risks_and_open_questions: "Risks and Open Questions",
  acceptance_criteria: "Acceptance Criteria",
  delivery_plan: "Delivery Plan",
};

export const fallbackPrd = (task: string, interview: InterviewTurn): PrdArtifact => ({
  documentTitle: "BleedingAgent Coding Agent PRD",
  sections: Object.entries(SECTION_TITLES).map(([key, title]) => ({
    key: key as PrdArtifact["sections"][number]["key"],
    title,
    body:
      key === "problem_statement"
        ? `Build BleedingAgent as an ACP coding-agent backend and self-evolving optimization harness. The bag command is the operator entrypoint for launching ACP, running maintenance flows, and inspecting artifacts. Initial task: ${task}`
        : key === "integrations_and_constraints"
          ? "Use Ax for agent/RLM orchestration. Use GPT-5.5 as master when OPENAI_API_KEY is present. Use the local MLX OpenAI-compatible endpoint as executor pool with default concurrency 16 and practical cap 24. Persist all measurements under .bag."
          : key === "acceptance_criteria"
            ? "The ACP server supports coding, planning, reporting, traces, metrics, YOLO/Safe policy, MCP visibility, and hidden operator maintenance flows. The bag operator command can launch ACP, inspect health, and run maintenance commands. Each run stores JSON/Markdown artifacts, telemetry events, step metrics, self-evaluation, and optimization evidence."
            : key === "risks_and_open_questions"
              ? interview.openQuestions.join("\n")
              : "Generated by deterministic fallback until a master model is configured.",
  })),
});

export const renderPrdMarkdown = (artifact: PrdArtifact): string =>
  [`# ${artifact.documentTitle}`, ...artifact.sections.map((section) => `## ${section.title}\n\n${section.body}`)].join(
    "\n\n",
  );

export const generatePrd = async (input: {
  router: LlmRouter;
  task: string;
  interview: InterviewTurn;
  repoContext: string;
  knowledge: string;
}): Promise<PrdArtifact> => {
  const fallback = fallbackPrd(input.task, input.interview);
  if (!input.router.masterAvailable) {
    return fallback;
  }

  const raw = await input.router.chatText({
    role: "master",
    json: true,
    maxTokens: 5000,
    purpose: "prd-generator",
    messages: [
      {
        role: "system",
        content:
          'You write compact engineering PRDs for coding agents. Return JSON ONLY (no prose, no code fences) with documentTitle (string) and sections (array of {key,title,body}). The "key" field MUST be exactly one of: table_of_contents, users_and_jobs, problem_statement, product_scope, user_workflows, functional_requirements, integrations_and_constraints, risks_and_open_questions, acceptance_criteria, delivery_plan. Do not invent other keys.',
      },
      {
        role: "user",
        content: [
          `Task:\n${input.task}`,
          `Interview:\n${JSON.stringify(input.interview, null, 2)}`,
          `Knowledge:\n${input.knowledge.slice(0, 6000)}`,
          `Repo context:\n${input.repoContext.slice(0, 16000)}`,
        ].join("\n\n"),
      },
    ],
  });

  const candidate = parseJsonObject(raw, fallback);
  const fullParse = PrdArtifactSchema.safeParse(candidate);
  if (fullParse.success) {
    return fullParse.data;
  }
  // Per-section salvage: keep every section the model produced that parses
  // individually; only fall back to deterministic content for the rest. This
  // beats the all-or-nothing fallback that previously erased a whole PRD just
  // because one enum drifted or one section was malformed.
  const fallbackByKey = new Map(fallback.sections.map((section) => [section.key, section]));
  const candidateRecord = (typeof candidate === "object" && candidate != null ? candidate : {}) as {
    documentTitle?: unknown;
    sections?: unknown;
  };
  const documentTitle =
    typeof candidateRecord.documentTitle === "string" && candidateRecord.documentTitle.trim().length > 0
      ? candidateRecord.documentTitle
      : fallback.documentTitle;
  const candidateSections = Array.isArray(candidateRecord.sections) ? candidateRecord.sections : [];
  const accepted = new Map<PrdArtifact["sections"][number]["key"], PrdArtifact["sections"][number]>();
  for (const raw of candidateSections) {
    if (raw == null || typeof raw !== "object") continue;
    const sectionRecord = raw as { key?: unknown; title?: unknown; body?: unknown };
    const keyParse = PrdSectionKeySchema.safeParse(sectionRecord.key);
    if (!keyParse.success) continue;
    if (typeof sectionRecord.body !== "string" || sectionRecord.body.trim().length === 0) continue;
    // First-write-wins: if the model emits two sections with the same key,
    // keep the first valid one (matches natural reading order, avoids
    // silently downgrading good content with a later worse copy).
    if (accepted.has(keyParse.data)) continue;
    accepted.set(keyParse.data, {
      key: keyParse.data,
      title: typeof sectionRecord.title === "string" && sectionRecord.title.length > 0
        ? sectionRecord.title
        : (fallbackByKey.get(keyParse.data)?.title ?? keyParse.data),
      body: sectionRecord.body,
    });
  }
  const sections = fallback.sections.map((section) => accepted.get(section.key) ?? section);
  return { documentTitle, sections };
};
